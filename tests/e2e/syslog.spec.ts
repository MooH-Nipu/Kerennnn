import { test, expect } from '@playwright/test';
import { readFileSync } from 'node:fs';
import { expectNoHorizontalOverflow, installEnvSession, dismissUpdateToast } from './helpers';

const fortigate = '<45>date=2026-10-27 time=13:39:17 devname="xxx" devid="xxx" eventtime=xxx tz="+0800" logid="0000000020" type="traffic" subtype="forward" level="notice" vd="xxx" srcip=xxx srcname="xxx" srcport=39600 srcintf="xxx" srcintfrole="lan" dstip=xxx dstport=xxx dstintf="xxx" dstintfrole="xxx" srcuuid="xxx" dstuuid="xxx" srccountry="Reserved" dstcountry="Indonesia" sessionid=xxx proto=17 action="accept" policyid=36 policytype="policy" poluuid="xxx" policyname="xxx" service="udp/9253" trandisp="snat" transip=xxx transport=39600 appid=xxx app="xxx" appcat="xxx" apprisk="xxx" applist="default" duration=139 sentbyte=1440 rcvdbyte=0 sentpkt=20 rcvdpkt=0 vwlid=1 vwlquality="Seq_num(1 wan2 virtual-wan-link), alive, selected" vwlname="xxx" sentdelta=1440 rcvddelta=0 durationdelta=139 sentpktdelta=20 rcvdpktdelta=0 srchwvendor="Samsung" devtype="Phone" srcfamily="Galaxy" osname="Android" srchwversion="A" srcswversion="16" mastersrcmac="1a:35:53:12:e4:da" srcmac="1a:35:53:12:e4:da" srcserver=0';

test('syslog mixed formats, validation, raw preservation, export and narrow layout', async ({ page, context, baseURL }, testInfo) => {
  console.log(`QA identity: ${process.env.E2E_AUTO_L1_USERNAME}`);
  await installEnvSession(context, baseURL!, 'l1');
  await context.grantPermissions(['clipboard-read', 'clipboard-write']);
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.addInitScript(() => localStorage.setItem('socToolboxActiveTab_l1', 'syslog'));
  await page.goto('/');
  await dismissUpdateToast(page);
  const baselineErrors = [...errors];
  await expect(page.getByRole('heading', { name: 'Log Formatter', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Log Formatter', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Syslog Formatter', exact: true })).toHaveCount(0);
  await expect(page.getByRole('combobox')).toHaveCount(0);
  await page.getByLabel('Log input', { exact: true }).fill(fortigate);
  await expect(page.locator('.syslog-record h3')).toContainText('FortiGate / key-value · VALID');
  await page.getByRole('button', { name: 'Copy hasil', exact: true }).click();
  expect(await page.evaluate(() => navigator.clipboard.readText())).toContain('vwlquality: Seq_num(1 wan2 virtual-wan-link), alive, selected');
  await page.getByRole('button', { name: 'Example mixed' }).click();
  await page.getByRole('button', { name: 'Format', exact: true }).click();
  await expect(page.getByRole('status').filter({ hasText: '3 valid' })).toContainText('0 invalid');
  await expect(page.locator('.syslog-record').first()).toContainText('timezone: null');
  await expect(page.locator('.syslog-record').nth(1)).toContainText('local4');
  await page.getByRole('button', { name: 'Copy JSON', exact: true }).click();
  const copied = JSON.parse(await page.evaluate(() => navigator.clipboard.readText()));
  expect(copied.map((r: { format: string }) => r.format)).toEqual(['RFC 3164', 'RFC 5424', 'FortiGate / key-value']);
  const [download] = await Promise.all([page.waitForEvent('download'), page.getByRole('button', { name: 'Download JSON' }).click()]);
  expect(download.suggestedFilename()).toBe('syslog.json');
  expect(JSON.parse(readFileSync((await download.path())!, 'utf8'))).toEqual(copied);
  await page.getByRole('button', { name: 'Copy text', exact: true }).click();
  expect(await page.evaluate(() => navigator.clipboard.readText())).toContain('Year and timezone are absent');
  await page.getByLabel('Log input', { exact: true }).fill(fortigate);
  await page.getByRole('button', { name: 'Format', exact: true }).click();
  await expect(page.locator('.syslog-record h3')).toContainText('FortiGate / key-value · VALID');
  await expect(page.locator('.syslog-record > pre')).toContainText('vwlquality: Seq_num(1 wan2 virtual-wan-link), alive, selected');
  await expect(page.locator('.syslog-record > pre')).toContainText('srcserver: 0');
  await page.locator('.syslog-record summary').click();
  await expect(page.locator('.syslog-record details pre')).toHaveText(fortigate);
  await page.getByRole('button', { name: 'Copy JSON', exact: true }).click();
  const vendor = JSON.parse(await page.evaluate(() => navigator.clipboard.readText()));
  expect(vendor[0].raw).toBe(fortigate);
  expect(vendor[0].fields).toHaveLength(62);
  expect(vendor[0].fields.every((f: { value: unknown }) => typeof f.value === 'string')).toBe(true);
  expect(vendor[0].fields.find((f: { name: string }) => f.name === 'vwlquality').value).toBe('Seq_num(1 wan2 virtual-wan-link), alive, selected');
  const [vendorDownload] = await Promise.all([page.waitForEvent('download'), page.getByRole('button', { name: 'Download JSON' }).click()]);
  expect(JSON.parse(readFileSync((await vendorDownload.path())!, 'utf8'))).toEqual(vendor);
  await page.getByRole('button', { name: 'Copy text', exact: true }).click();
  const vendorText = await page.evaluate(() => navigator.clipboard.readText());
  expect(vendorText).toContain('eventtime: xxx');
  expect(vendorText).toContain('vwlquality: Seq_num(1 wan2 virtual-wan-link), alive, selected');
  await expectNoHorizontalOverflow(page);
  await page.screenshot({ path: `/home/pebry/.hermes/cache/scratch/syslog-qa/fortigate-${testInfo.project.name}.png`, fullPage: true });
  await page.getByLabel('Log input', { exact: true }).fill('id=007 id=9007199254740993123 empty=""\na="unterminated\na="ok"garbage');
  await page.getByRole('button', { name: 'Format', exact: true }).click();
  await expect(page.getByRole('status').filter({ hasText: '1 valid' })).toContainText('2 invalid');
  await expect(page.locator('.syslog-record').first()).toContainText('Duplicate key: id');
  await expect(page.locator('.syslog-record').first()).toContainText('id: 007');
  await expect(page.locator('.syslog-record').first()).toContainText('id: 9007199254740993123');
  await expect(page.locator('.syslog-record--invalid').first()).toContainText('Unterminated key-value quote');
  await expect(page.locator('.syslog-record--invalid').nth(1)).toContainText('Trailing garbage');
  const raw = '<0>1 - - - - - [a x="<script>"][b y="ok"]  message  ';
  await page.getByLabel('Log input', { exact: true }).fill(raw + '\n<192>bad');
  await expect(page.getByRole('button', { name: 'Copy JSON', exact: true })).toBeDisabled();
  await page.getByRole('button', { name: 'Format', exact: true }).click();
  await expect(page.locator('.syslog-record--invalid')).toContainText('PRI must be <0> through <191>');
  await page.locator('.syslog-record').first().getByText('Original / raw record').click();
  await expect(page.locator('.syslog-record').first().locator('details pre')).toHaveText(raw);
  await expectNoHorizontalOverflow(page);
  await page.screenshot({ path: `/home/pebry/.hermes/cache/scratch/syslog-qa/${testInfo.project.name}.png`, fullPage: true });
  await page.getByLabel('Log input', { exact: true }).fill('x'.repeat(262145));
  await expect(page.getByRole('alert')).toContainText('nothing processed');
  await expect(page.locator('.syslog-record')).toHaveCount(0);
  const indicators = '192.0.2.10 bad.example https://bad.example/path user@bad.example ' + 'a'.repeat(64);
  await page.getByLabel('Log input', { exact: true }).fill('msg="unterminated ' + indicators);
  await page.getByRole('button', { name: 'Extract IOCs', exact: true }).click();
  const iocs = page.getByRole('region', { name: 'Syslog extracted IOCs' });
  await expect(iocs.getByRole('textbox')).toHaveValue(/# IPs \(1\)\n\[field unknown\]=192\.0\.2\.10/);
  for (const heading of ['# Domains', '# URLs', '# Hashes', '# Emails']) await expect(iocs.getByRole('textbox')).toHaveValue(new RegExp(heading));
  await iocs.getByRole('button').click();
  expect(await page.evaluate(() => navigator.clipboard.readText())).toContain('user@bad.example');
  await page.locator('#log-input').fill('{"ip":"192.0.2.10","n":1}');
  await expect(page.getByRole('textbox', { name: 'Highlighted output' })).toContainText('"ip": "192.0.2.10"');
  await expect(page.locator('.ioc-mark').filter({ hasText: '192.0.2.10' })).toHaveCount(1);
  await page.getByRole('button', { name: 'Minify', exact: true }).click();
  await expect(page.getByRole('textbox', { name: 'Highlighted output' })).toHaveText('{"ip":"192.0.2.10","n":1}');
  await page.locator('#log-input').fill('{ "ip": "192.0.2.10" }\n{ "domain": "bad.example" }');
  await expect(page.getByRole('textbox', { name: 'Highlighted output' })).toHaveText('{"ip":"192.0.2.10"}\n{"domain":"bad.example"}');
  await page.getByRole('button', { name: 'Beautify', exact: true }).click();
  await expect(page.getByRole('textbox', { name: 'Highlighted output' })).toContainText('"domain": "bad.example"');
  await page.getByRole('button', { name: 'Extract IOCs', exact: true }).click();
  await page.locator('#log-input').fill('not JSON ' + indicators);
  await expect(page.getByRole('textbox', { name: 'Output', exact: true })).toHaveValue(/# IPs/);
  await page.locator('#log-input').fill('{"source":{"ip":"192.0.2.10"},"destination":{"ip":"192.0.2.10"},"url":"https://bad.example/path"}');
  await expect(page.getByRole('textbox', { name: 'Output', exact: true })).toHaveValue(/source.ip=192\.0\.2\.10/);
  await expect(page.getByRole('textbox', { name: 'Output', exact: true })).toHaveValue(/destination.ip=192\.0\.2\.10/);
  await page.locator('#log-input').fill('{"source":{"ip":"192.0.2.10"}}\n{"destination":{"ip":"192.0.2.10"}}');
  await expect(page.getByRole('textbox', { name: 'Output', exact: true })).toHaveValue(/line\[1\].source.ip=192\.0\.2\.10/);
  await expect(page.getByRole('textbox', { name: 'Output', exact: true })).toHaveValue(/line\[2\].destination.ip=192\.0\.2\.10/);
  await page.locator('#log-input').fill('srcip=192.0.2.10 dstip=192.0.2.10 hostname="bad.example"');
  await page.getByRole('button', { name: 'Extract IOCs', exact: true }).click();
  const originOutput = page.getByRole('region', { name: 'Syslog extracted IOCs' }).getByRole('textbox');
  await expect(originOutput).toHaveValue(/srcip=192\.0\.2\.10/);
  await expect(originOutput).toHaveValue(/dstip=192\.0\.2\.10/);
  await expect(originOutput).toHaveValue(/hostname=bad\.example/);
  await page.getByRole('region', { name: 'Syslog extracted IOCs' }).getByRole('button').click();
  expect(await page.evaluate(() => navigator.clipboard.readText())).toContain('srcip=192.0.2.10');
  await expectNoHorizontalOverflow(page);
  await page.screenshot({ path: `/home/pebry/.hermes/cache/scratch/syslog-qa/json-${testInfo.project.name}.png`, fullPage: true });
  await page.getByLabel('Log input', { exact: true }).fill(fortigate);
  await expect(page.locator('.syslog-record h3')).toContainText('FortiGate / key-value · VALID');
  expect(errors).toEqual(baselineErrors);
});
